# Defining a list

myFruitList = ["apple", "banana", "cherry"]
print(myFruitList)
print(type(myFruitList))

# Accessing a list by position
print(myFruitList[0])
print(myFruitList[1])
print(myFruitList[2])

# Changing the values in a list
myFruitList[1] = "orange"
print(myFruitList)
myFruitList[2] = "watermelon"
print(myFruitList)